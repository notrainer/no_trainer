import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const cssSource = path.join(root, "assets/main.css");
const css = await fs.readFile(cssSource, "utf8");
// Only the viewer's custom rules are local; Tailwind comes from the CDN.
const viewerCSS = css.slice(css.indexOf(".nmap-viewer {"));
const js = await esbuild.build({
  entryPoints: [path.join(root, "assets/nmap-visualizer.ts")],
  bundle: true,
  write: false,
  minify: false,
  charset: "utf8",
  format: "iife",
  platform: "browser",
});
const template = await fs.readFile(
  path.join(root, "templates/partials/nmap-visualizer.html"),
  "utf8",
);
const body = template.replace(/^\{\{ define "nmap-visualizer" \}\}\s*/, "")
  .replace(/\s*\{\{ end \}\}\s*$/, "");
const output = path.join(root, "standalone/nmap-visualizer.html");
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, `<!doctype html>
<!-- Generated by node build-standalone.mjs; Tailwind loads from the CDN. -->
<html lang="de" class="dark">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="dark">
  <title>Nmap XML Visualizer</title>
  <script src="https://cdn.jsdelivr.net/npm/@tailwindcss/browser@4.3.3/dist/index.global.js"></script>
  <style>${viewerCSS.replace(/<\/style/gi, "<\\/style")}
  body { min-height: 100vh; background: #020617; }
  </style>
</head>
<body>
<main>${body}</main>
<script>
${js.outputFiles[0].text.replace(/<\/script/gi, "<\\/script")}</script>
</body>
</html>
`);
console.log(`Created ${output}`);
